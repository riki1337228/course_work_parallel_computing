#!/usr/bin/env python3
"""Deterministic generator of a synthetic English text corpus.

Layout produced in DATASET_PATH (default /data):

    documents/document_000001.txt ... document_NNNNNN.txt
    metadata.json          (written last; acts as the "dataset complete" marker)

Each document:
  * has a primary topic (~70 % of sentences), a secondary topic (~25 %) and random
    "noise" sentences from any topic (~5 %);
  * focuses on a random subset of its topic vocabulary, so term frequencies differ
    between documents of the same topic (meaningful TF-IDF ranking);
  * mentions 2-3 unique synthetic entity names (rare terms for exact-match tests);
  * consists of sentences generated from templates (see dataset_vocabulary.py).

Determinism: document i is generated by random.Random(f"{seed}:{i}"), so the corpus
is byte-identical for the same parameters regardless of the number of worker
processes. The script is idempotent: if metadata.json matches the requested
parameters, generation is skipped.

Environment variables / CLI options:
    DATASET_PATH        output directory           (default /data)
    DATASET_DOCUMENTS   number of documents        (default 20000, minimum 1)
    DATASET_TARGET_MB   target total size in MiB   (default 2100, i.e. > 2 GiB)
    DATASET_SEED        random seed                (default 42)
    DATASET_WORKERS     parallel processes         (default: CPU count)
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dataset_vocabulary import (CITIES, FIRST_NAMES, GENERIC_ADJECTIVES, LAST_NAMES,  # noqa: E402
                                ORGANIZATIONS, SYLLABLES, TEMPLATES, TITLE_TEMPLATES, TOPICS)

GENERATOR_VERSION = 1
TOPIC_NAMES = sorted(TOPICS)


def document_name(index: int) -> str:
    return f"document_{index:06d}"


def make_entity(rng: random.Random) -> str:
    word = "".join(rng.choice(SYLLABLES) for _ in range(rng.randint(2, 3)))
    return word.capitalize() + rng.choice(["", "ia", "on", "ex", "is"])


class TopicView:
    """A document-specific weighted view on one topic's vocabulary."""

    def __init__(self, rng: random.Random, topic: str):
        vocab = TOPICS[topic]
        nouns = list(vocab["nouns"])
        rng.shuffle(nouns)
        focus = rng.randint(5, 10)
        # Focus nouns are 6x more likely than the rest -> different TF per document.
        self.nouns = nouns
        self.noun_weights = [6.0 if i < focus else 1.0 for i in range(len(nouns))]
        self.adjectives = vocab["adjectives"]
        self.verbs = vocab["verbs"]

    def noun(self, rng: random.Random) -> str:
        return rng.choices(self.nouns, weights=self.noun_weights, k=1)[0]


def fill(template: str, rng: random.Random, view: TopicView, entities: list[str]) -> str:
    text = template.format(
        n1=view.noun(rng), n2=view.noun(rng), n3=view.noun(rng),
        a=rng.choice(view.adjectives), v=rng.choice(view.verbs), g=rng.choice(GENERIC_ADJECTIVES),
        org=rng.choice(ORGANIZATIONS), person=f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}",
        city=rng.choice(CITIES), year=rng.randint(1890, 2025), num=rng.randint(2, 500),
        entity=rng.choice(entities),
    )
    return text[0].upper() + text[1:]


def generate_document(seed: int, index: int, target_bytes: int) -> tuple[str, dict]:
    rng = random.Random(f"{seed}:{index}")
    primary, secondary = rng.sample(TOPIC_NAMES, 2)
    views = {primary: TopicView(rng, primary), secondary: TopicView(rng, secondary)}
    entities = [make_entity(rng) for _ in range(rng.randint(2, 3))]
    size = int(target_bytes * rng.uniform(0.5, 1.5))

    title = fill(rng.choice(TITLE_TEMPLATES), rng, views[primary], entities)
    parts = [title, "\n\n"]
    length = len(title) + 2
    while length < size:
        sentences = []
        for _ in range(rng.randint(4, 9)):
            roll = rng.random()
            if roll < 0.70:
                view = views[primary]
            elif roll < 0.95:
                view = views[secondary]
            else:
                noise = rng.choice(TOPIC_NAMES)
                view = views.setdefault(noise, TopicView(rng, noise))
            sentences.append(fill(rng.choice(TEMPLATES), rng, view, entities))
        paragraph = " ".join(sentences) + "\n\n"
        parts.append(paragraph)
        length += len(paragraph)
    text = "".join(parts)
    meta = {"doc_id": document_name(index), "topics": [primary, secondary], "entities": entities,
            "bytes": len(text.encode("ascii"))}
    return text, meta


def write_range(args: tuple[str, int, int, int, int]) -> list[dict]:
    out_dir, seed, start, end, target_bytes = args
    docs_dir = Path(out_dir) / "documents"
    metas = []
    for index in range(start, end):
        text, meta = generate_document(seed, index, target_bytes)
        with open(docs_dir / f"{meta['doc_id']}.txt", "w", encoding="ascii", newline="\n") as f:
            f.write(text)
        metas.append(meta)
    return metas


def already_generated(out_dir: Path, params: dict) -> bool:
    meta_path = out_dir / "metadata.json"
    if not meta_path.is_file():
        return False
    try:
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False
    if any(meta.get(k) != v for k, v in params.items()):
        return False
    docs_dir = out_dir / "documents"
    present = sum(1 for _ in docs_dir.glob("document_*.txt")) if docs_dir.is_dir() else 0
    return present == params["documents"]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", default=os.environ.get("DATASET_PATH", "/data"))
    parser.add_argument("--documents", type=int, default=int(os.environ.get("DATASET_DOCUMENTS", "20000")))
    parser.add_argument("--target-mb", type=float, default=float(os.environ.get("DATASET_TARGET_MB", "2100")))
    parser.add_argument("--seed", type=int, default=int(os.environ.get("DATASET_SEED", "42")))
    parser.add_argument("--workers", type=int, default=int(os.environ.get("DATASET_WORKERS", os.cpu_count() or 4)))
    args = parser.parse_args()

    if args.documents < 1 or args.target_mb <= 0:
        print("error: documents must be >= 1 and target size > 0", file=sys.stderr)
        return 2

    out_dir = Path(args.output)
    params = {"generator_version": GENERATOR_VERSION, "seed": args.seed, "documents": args.documents,
              "target_bytes": int(args.target_mb * 1024 * 1024)}
    if already_generated(out_dir, params):
        meta = json.loads((out_dir / "metadata.json").read_text(encoding="utf-8"))
        print(f"[dataset-init] dataset already present: {meta['documents']} documents, "
              f"{meta['total_bytes'] / 1024 ** 2:.1f} MiB in {out_dir} - skipping generation", flush=True)
        return 0

    docs_dir = out_dir / "documents"
    docs_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "metadata.json").unlink(missing_ok=True)  # incomplete until rewritten at the end
    for stale in docs_dir.glob("document_*.txt"):
        stale.unlink()

    per_doc = params["target_bytes"] // args.documents
    workers = max(1, args.workers)
    chunk = max(1, min(250, args.documents // (workers * 4) or 1))
    ranges = [(str(out_dir), args.seed, s, min(s + chunk, args.documents + 1), per_doc)
              for s in range(1, args.documents + 1, chunk)]
    print(f"[dataset-init] generating {args.documents} documents (~{args.target_mb:.0f} MiB, seed={args.seed}) "
          f"with {workers} processes into {docs_dir}", flush=True)

    started = time.time()
    metas: list[dict] = []
    total = 0
    step = max(1, args.documents // 10)
    next_report = step
    with ProcessPoolExecutor(max_workers=workers) as pool:
        for part in pool.map(write_range, ranges):
            metas.extend(part)
            total += sum(m["bytes"] for m in part)
            if len(metas) >= next_report:
                next_report += step
                print(f"[dataset-init] {len(metas)}/{args.documents} documents, {total / 1024 ** 2:.0f} MiB, "
                      f"{time.time() - started:.0f} s", flush=True)

    metas.sort(key=lambda m: m["doc_id"])
    metadata = {
        **params,
        "generator": "scripts/generate_dataset.py (template-based synthetic English corpus)",
        "format": "plain text, ASCII, one document per .txt file",
        "total_bytes": total,
        "topics": TOPIC_NAMES,
        "files": metas,
    }
    tmp = out_dir / "metadata.json.tmp"
    tmp.write_text(json.dumps(metadata, indent=1), encoding="utf-8")
    tmp.replace(out_dir / "metadata.json")
    print(f"[dataset-init] done: {len(metas)} documents, {total / 1024 ** 2:.1f} MiB "
          f"({total / 1024 ** 3:.2f} GiB) in {time.time() - started:.0f} s", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
